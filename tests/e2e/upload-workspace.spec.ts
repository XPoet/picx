import { Buffer } from 'node:buffer'
import { fixturePngBase64 } from '../fixtures/ui-redesign'
import { expect, test } from './fixtures'

const png = (name = 'same.png') => ({ name, mimeType: 'image/png', buffer: Buffer.from(fixturePngBase64, 'base64') })

test('持续追加同名图片、MP4 与粘贴，输入内不接管粘贴', async ({ page, picx }, info) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await picx.open('/upload', { savedRepository: true, processingDisabled: true })
  const input = page.locator('.getting-images-container input[type=file]')
  await input.setInputFiles(png())
  await expect(page.locator('.uploaded-item')).toHaveCount(1)
  await input.setInputFiles([png(), { name: 'clip.mp4', mimeType: 'video/mp4', buffer: Buffer.from('fixture-mp4') }])
  await expect(page.locator('.uploaded-item')).toHaveCount(3)
  await page.evaluate((base64) => {
    const file = new File([Uint8Array.from(atob(base64), char => char.charCodeAt(0))], 'pasted.png', { type: 'image/png' })
    const clipboard = new DataTransfer()
    clipboard.items.add(file)
    document.body.dispatchEvent(new ClipboardEvent('paste', { clipboardData: clipboard, bubbles: true, cancelable: true }))
  }, fixturePngBase64)
  await expect(page.locator('.uploaded-item')).toHaveCount(4)
  await expect(page.getByRole('button', { name: '选择图片或 MP4', exact: true })).toBeVisible()
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p3/t020-intake-1440.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p3/t020-intake-375.png', fullPage: true })
})

test('选图后容器恢复原有高度并等高，提示样式一致且队列独立滚动', async ({ page, picx }) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await picx.open('/upload', { savedRepository: true, processingDisabled: true })
  const intake = page.locator('.getting-images-container')
  const snapshot = () => intake.evaluate((element) => {
    const style = getComputedStyle(element)
    const heading = getComputedStyle(element.querySelector('h2')!)
    return { text: element.textContent, border: style.border, radius: style.borderRadius, gap: style.gap, fontSize: heading.fontSize, fontWeight: heading.fontWeight }
  })
  const empty = await snapshot()
  const input = page.locator('.getting-images-container input[type=file]')
  await input.setInputFiles(['coast', 'forest', 'dunes', 'architecture', 'lake', 'flowers', 'city'].map(name => png(`${name}.png`)))
  await expect(page.locator('.uploaded-item')).toHaveCount(7)
  expect(await snapshot()).toEqual(empty)
  expect(await page.locator('.upload-page-left').evaluate(element => element.getBoundingClientRect().height))
    .toBe(await intake.evaluate(element => element.getBoundingClientRect().height))
  await expect(page.locator('.queue-heading')).toContainText('7 张')
  await expect(page.locator('.upload-page-left')).toHaveCSS('width', '280px')
  await expect(page.locator('.upload-stage')).toHaveCSS('height', '704px')
  await expect(page.locator('.upload-stage')).toHaveCSS('gap', '16px')
  await expect(page.locator('.upload-settings-panel')).toHaveCSS('width', '320px')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '/private/tmp/picx-upload-selected-desktop.png' })
  await input.setInputFiles(Array.from({ length: 12 }, (_, index) => png(`more-${index}.png`)))
  await expect(page.locator('.uploaded-item')).toHaveCount(19)
  const list = page.locator('.queue-scrollbar .el-scrollbar__wrap')
  expect(await list.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await list.hover()
  await page.mouse.wheel(0, 300)
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(page.locator('.queue-add')).toBeInViewport()
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '/private/tmp/picx-upload-selected-mobile.png' })
  for (let index = 0; index < 19; index++)
    await page.locator('.queue-remove').first().click()
  await expect(page.locator('.upload-page-left')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '选择图片或 MP4', exact: true })).toBeVisible()
})
