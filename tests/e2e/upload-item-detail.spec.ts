import { Buffer } from 'node:buffer'
import { fixturePngBase64 } from '../fixtures/ui-redesign'
import { expect, test } from './fixtures'

test('文件详情按需重命名、预览短哈希，关闭不保存且重复打开保持稳定', async ({ page, picx }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  if (info.project.name === 'desktop-chrome')
    await page.setViewportSize({ width: 1440, height: 1000 })
  await picx.open('/upload', { savedRepository: true, processingDisabled: true })
  await page.locator('.getting-images-container input[type=file]').setInputFiles({ name: 'coast.png', mimeType: 'image/png', buffer: Buffer.from(fixturePngBase64, 'base64') })
  const row = page.locator('.uploaded-item').first()
  const dialog = page.getByRole('dialog', { name: '文件详情', exact: true })
  const input = dialog.getByRole('textbox', { name: '新文件名（不含扩展名）', exact: true })
  const preview = dialog.locator('.upload-item-detail__result strong')
  await row.locator('.media-thumbnail').click()
  await expect(dialog).toBeVisible()
  await expect(input).toHaveCount(0)
  await expect(dialog.getByRole('checkbox', { name: '添加前缀', exact: true })).toHaveCount(0)
  await expect(dialog.getByText('文件名前缀', { exact: true })).toHaveCount(0)
  const box = await dialog.locator('.upload-item-detail__preview').boundingBox()
  expect(box!.height).toBeGreaterThanOrEqual(200)
  if (info.project.name === 'desktop-chrome')
    expect(box!.height).toBeGreaterThan(260)
  await dialog.getByRole('checkbox', { name: '哈希化', exact: true }).press('Space')
  await expect(preview).toHaveText(/^coast\.[a-f0-9]{6}\.png$/)
  const hashName = await preview.textContent()
  await dialog.getByRole('checkbox', { name: '重命名', exact: true }).press('Space')
  await expect(input).toBeVisible()
  await input.fill('new/coast')
  await expect(dialog.getByRole('button', { name: '保存文件名', exact: true })).toBeDisabled()
  await input.fill('New coast')
  await expect(preview).toHaveText(/^New-coast\.[a-f0-9]{6}\.png$/)
  await dialog.getByRole('checkbox', { name: '重命名', exact: true }).press('Space')
  await expect(input).toHaveCount(0)
  await expect(preview).toHaveText(hashName!)
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(row.locator('.queue-filename')).toHaveText('coast.png')
  await row.locator('.media-thumbnail').click()
  await expect(input).toHaveCount(0)
  await expect(dialog.getByRole('checkbox', { name: '哈希化', exact: true })).not.toBeChecked()
  await dialog.getByRole('checkbox', { name: '哈希化', exact: true }).press('Space')
  await expect(preview).toHaveText(hashName!)
  await dialog.getByRole('checkbox', { name: '重命名', exact: true }).press('Space')
  await input.fill('New coast')
  await page.screenshot({ path: `/private/tmp/picx-file-detail-${info.project.name}.png` })
  await dialog.getByRole('button', { name: '保存文件名', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row.locator('.queue-filename')).toHaveText(/^New-coast\.[a-f0-9]{6}\.png$/)
  await row.locator('.media-thumbnail').click()
  await expect(input).toHaveValue('New coast')
  await expect(preview).toHaveText(await row.locator('.queue-filename').textContent() ?? '')
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  if (info.project.name === 'desktop-chrome')
    await page.setViewportSize({ width: 1280, height: 720 })
  await page.screenshot({ path: `/private/tmp/picx-file-detail-compact-${info.project.name}.png` })
  await expect(preview).toBeInViewport()
  await expect(dialog.getByRole('button', { name: '保存文件名', exact: true })).toBeInViewport()
})

for (const locale of [
  { language: 'en', title: 'File details', rename: 'Rename', name: 'New name (without extension)', save: 'Save filename' },
  { language: 'zh-TW', title: '檔案詳情', rename: '重新命名', name: '新檔名（不含副檔名）', save: '儲存檔名' },
] as const) {
  test(`文件详情 ${locale.language} 深色模式布局与保存`, async ({ page, picx }, info) => {
    await picx.open('/upload', { savedRepository: true, processingDisabled: true, theme: 'dark', language: locale.language })
    await page.locator('.getting-images-container input[type=file]').setInputFiles({ name: 'coast.png', mimeType: 'image/png', buffer: Buffer.from(fixturePngBase64, 'base64') })
    const row = page.locator('.uploaded-item').first()
    await row.locator('.media-thumbnail').click()
    const dialog = page.getByRole('dialog', { name: locale.title, exact: true })
    await expect(dialog).toBeVisible()
    await dialog.getByRole('checkbox', { name: locale.rename, exact: true }).press('Space')
    await dialog.getByRole('textbox', { name: locale.name, exact: true }).fill('renamed')
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `/private/tmp/picx-file-detail-${locale.language}-${info.project.name}.png` })
    await dialog.getByRole('button', { name: locale.save, exact: true }).click()
    await expect(row.locator('.queue-filename')).toHaveText('renamed.png')
  })
}
