import { expect, openNavigation, test } from './fixtures'

test('快捷设置复用旧偏好，两页一致且目录入口保留', async ({ page, picx }, info) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await picx.open('/upload', { savedRepository: true, processingDisabled: true })
  const panel = page.getByRole('complementary', { name: '设置', exact: true })
  await expect(panel).toHaveCSS('width', '320px')
  await expect(panel.getByRole('combobox', { name: '链接格式' })).toHaveValue('raw')
  await expect(panel.getByRole('button', { name: /上传 0 个文件/ })).toBeDisabled()
  await panel.getByRole('switch', { name: '自动压缩', exact: true }).press('Space')
  await panel.getByRole('combobox', { name: '链接格式' }).selectOption('BBCode')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('PICX_IH_SETTINGS') ?? '{}').imageLinkFormat.enable)).toBe(true)
  await panel.getByRole('combobox', { name: '链接格式' }).selectOption('raw')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('PICX_IH_SETTINGS') ?? '{}').imageLinkFormat.enable)).toBe(false)
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p3/t024-settings-1440.png', fullPage: true })
  await openNavigation(page)
  await page.getByRole('link', { name: '图床设置', exact: true }).click()
  await page.locator('.el-collapse-item__header').filter({ hasText: '图片压缩' }).click()
  const compression = page.getByRole('switch', { name: '是否压缩图片', exact: true })
  await expect(compression).toBeChecked()
  await compression.press('Space')
  await openNavigation(page)
  await page.getByRole('link', { name: '上传图片', exact: true }).click()
  await expect(page.getByRole('switch', { name: '自动压缩', exact: true })).not.toBeChecked()
  await page.setViewportSize({ width: 768, height: 1024 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 375, height: 812 })
  await panel.getByRole('combobox', { name: '链接格式' }).scrollIntoViewIfNeeded()
  await expect(panel.getByRole('combobox', { name: '链接格式' })).toHaveCSS('font-size', '16px')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p3/t024-settings-375.png', fullPage: true })
  await page.getByRole('button', { name: '更改上传目录', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '配置上传目录', exact: true })).toBeVisible()
})
