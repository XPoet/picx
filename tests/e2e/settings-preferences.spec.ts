import { expect, test } from './fixtures'

test('旧命名、前缀草稿、编码器与水印参数在刷新后保留', async ({ page, picx }, info) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await picx.open('/settings', { savedRepository: true, settingsWritable: true })
  const processing = page.getByRole('region', { name: '上传处理', exact: true })
  await expect(processing.getByRole('button', { name: '保留原名', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(processing.getByRole('spinbutton', { name: '水印大小', exact: true })).toHaveValue('32')
  await processing.getByRole('switch', { name: '添加前缀', exact: true }).press('Space')
  const prefix = processing.getByRole('textbox', { name: '前缀内容', exact: true })
  await prefix.fill('picx-')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('PICX_IH_SETTINGS') ?? '{}').imageName.addPrefix.prefix)).toBe('legacy-')
  await prefix.press('Tab')
  await expect(processing.getByTestId('naming-preview')).toHaveText('picx-coast.png')
  await processing.getByRole('button', { name: '时间戳', exact: true }).click()
  await expect(prefix).toBeDisabled()
  await expect(prefix).toHaveValue('picx-')
  await expect(processing.getByTestId('naming-preview')).toHaveText(/^\d+\.png$/)
  await processing.getByRole('button', { name: '原名 + 哈希', exact: true }).click()
  await expect(prefix).toBeEnabled()
  await processing.getByRole('switch', { name: '是否压缩图片', exact: true }).press('Space')
  await processing.getByRole('radio', { name: /avif/ }).press('Space')
  await processing.getByRole('button', { name: '全屏', exact: true }).click()
  await expect(processing.getByRole('spinbutton', { name: '旋转角度', exact: true })).toBeVisible()
  const synced = page.waitForResponse(response => response.url().includes('/contents/.settings') && response.request().method() === 'PUT')
  await processing.getByRole('button', { name: '右下角', exact: true }).click()
  await expect(processing.getByRole('spinbutton', { name: '旋转角度', exact: true })).toHaveCount(0)
  await synced
  await page.reload()
  await expect(prefix).toHaveValue('picx-')
  await expect(processing.getByRole('radio', { name: /avif/ })).toBeChecked()
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p5/t035-settings-1440.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'desktop-chrome')
    await page.screenshot({ path: 'docs/UI/evidence/p5/t035-settings-375.png', fullPage: true })
})
