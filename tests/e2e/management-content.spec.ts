import process from 'node:process'
import { expect, test } from './management-fixture'

test('混合目录分区计数，搜索只过滤当前目录，切目录清词', async ({ page, management }, info) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await management.open()
  const folders = page.locator('.management-content > section').filter({ has: page.locator('.dir-card-list') })
  const media = page.locator('.management-content > section').filter({ has: page.locator('.image-card-list') })
  await expect(folders.getByRole('heading')).toHaveText('文件夹 2')
  await expect(media.getByRole('heading')).toHaveText('图片与视频 1')
  if (info.project.name === 'desktop-chrome' && process.env.PICX_CAPTURE_TASK === 'T030')
    await page.screenshot({ path: 'docs/UI/evidence/p4/t030-mixed-1440.png', fullPage: true })
  const search = page.getByPlaceholder('搜索文件夹或媒体名称', { exact: true })
  await search.fill('LAKE')
  await expect(page.getByText('当前目录没有匹配结果', { exact: true })).toBeVisible()
  expect(management.requests).toEqual([''])
  await page.getByRole('button', { name: '清空搜索', exact: true }).click()
  await search.fill('ALBUM')
  await expect(folders.getByRole('heading')).toHaveText('文件夹 1')
  await expect(media).toHaveCount(0)
  await page.getByTitle('进入文件夹 albums', { exact: true }).click()
  await expect(search).toHaveValue('')
  await expect(media.getByRole('heading')).toHaveText('图片与视频 2')
  await page.setViewportSize({ width: 375, height: 812 })
  await search.fill('absent')
  await expect(search).toHaveCSS('font-size', '16px')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'desktop-chrome' && process.env.PICX_CAPTURE_TASK === 'T030')
    await page.screenshot({ path: 'docs/UI/evidence/p4/t030-search-375.png', fullPage: true })
})

test('仅文件夹与空目录分别显示内容，排序保留源顺序与用户偏好', async ({ page, management }, info) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await management.open({ scenario: 'folders' })
  await expect(page.getByText('当前目录暂无图片或视频', { exact: true })).toBeVisible()
  if (info.project.name === 'desktop-chrome' && process.env.PICX_CAPTURE_TASK === 'T030')
    await page.screenshot({ path: 'docs/UI/evidence/p4/t030-folders-1440.png', fullPage: true })
  await page.locator('.management-summary').getByRole('combobox').press('Enter')
  await page.getByRole('option', { name: '名称降序', exact: true }).click()
  await expect(page.locator('.folder-name')).toHaveText(['empty', 'albums'])
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('PICX_IH_SETTINGS') ?? '{}').management.sort)
  expect(saved).toBe('nameDesc')
  const tree = await page.evaluate(() => JSON.parse(localStorage.getItem('PICX_IH_MANAGEMENT') ?? '{}'))
  expect(tree.childrenDirs.map((item: { dir: string }) => item.dir)).toEqual(['albums', 'empty'])
  await page.getByTitle('进入文件夹 empty', { exact: true }).click()
  await expect(page.getByText('当前目录为空', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '上传到当前目录', exact: true }).first()).toBeVisible()
})
